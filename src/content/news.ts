import type { NewsArticle, Weather } from '../types';
/** Template pieces. `when` filters (all optional); text may use {friend} {dish} {festival} {days} {served} {item} placeholders. */
export interface NewsTemplate extends Omit<NewsArticle, 'id'> {
  key: string;
  when?: { minDay?: number; maxDay?: number; chapterAtLeast?: number; season?: 'winter' | 'spring' | 'summer' | 'autumn'; festivalSoon?: boolean; konbiniOpen?: boolean; friendMet?: boolean; weather?: Weather };
  weight?: number;
}

type Extra = Partial<Pick<NewsTemplate, 'sticker' | 'regular' | 'when' | 'weight'>>;
const t = (key: string, section: NewsArticle['section'], title: string, text: string, extra: Extra = {}): NewsTemplate =>
  ({ key, section, title, text, ...extra });

